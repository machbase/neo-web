-- Verified: Neo v8.7.0-rc2-snapshot (5e0c309d), engine dev-4158.
-- These are test data definitions, not queries executed by the viewer.

CREATE TAG TABLE DV_ARRAY_TEST (
    NAME VARCHAR(80) PRIMARY KEY,
    TIME DATETIME BASETIME,
    CHANNELS DOUBLE[4]
);
INSERT INTO DV_ARRAY_TEST VALUES ('sensor.a', '2026-09-28 00:00:00', [10,NULL,30,40]);
INSERT INTO DV_ARRAY_TEST VALUES ('sensor.a', '2026-09-28 00:00:01', [NULL,NULL,NULL,NULL]);
INSERT INTO DV_ARRAY_TEST VALUES ('sensor.a', '2026-09-28 00:00:02', NULL);
INSERT INTO DV_ARRAY_TEST VALUES ('sensor.a', '2026-09-28 00:00:03', [50,60,70,80]);

CREATE TAG TABLE DV_ARRAY_DECIMAL_TEST (
    NAME VARCHAR(80) PRIMARY KEY,
    TIME DATETIME BASETIME,
    VALUE DECIMAL(12,4)[2]
);
INSERT INTO DV_ARRAY_DECIMAL_TEST VALUES ('sensor.a', '2026-09-28 00:00:00', [1.2500,12345678.1234]);

CREATE TAG TABLE DV_ARRAY_INT64_TEST (
    NAME VARCHAR(80) PRIMARY KEY,
    TIME DATETIME BASETIME,
    VALUE INT64[2]
);
INSERT INTO DV_ARRAY_INT64_TEST VALUES ('sensor.a', '2026-09-28 00:00:00', [9007199254740993,9223372036854775806]);

-- LENGTH is cardinality for an ARRAY, not the serialized payload size.
SELECT MC.NAME, MC.TYPE, MC.LENGTH, MC.PRECISION, MC.SCALE
FROM M$SYS_COLUMNS MC, M$SYS_TABLES MT
WHERE MC.TABLE_ID=MT.ID AND MC.DATABASE_ID=MT.DATABASE_ID
AND MT.NAME IN ('DV_ARRAY_TEST','DV_ARRAY_DECIMAL_TEST','DV_ARRAY_INT64_TEST');

-- Whole NULL, all-elements NULL, and some-elements NULL remain different raw values.
SELECT TIME, CHANNELS, CHANNELS[0] AS AV0, CHANNELS[1] AS AV1
FROM DV_ARRAY_TEST WHERE NAME='sensor.a' ORDER BY TIME, CHANNELS[0], CHANNELS[1];

-- Compare the raw HTTP response tokens before a normal JavaScript JSON.parse.
SELECT VALUE, VALUE[0], VALUE[1] FROM DV_ARRAY_INT64_TEST;
SELECT VALUE, VALUE[0], VALUE[1] FROM DV_ARRAY_DECIMAL_TEST;
